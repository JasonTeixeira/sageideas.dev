import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
const require = createRequire(new URL('../../package.json', import.meta.url));
const { chromium } = require('playwright');
const { default: AxeBuilder } = await import(require.resolve('@axe-core/playwright'));
const { strict: assert } = await import('node:assert');
const out = '/tmp/studio-consolidation-proof';
await mkdir(out,{recursive:true});
const browser = await chromium.launch({channel:'chrome',headless:true});
try {
 const context = await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
 const page=await context.newPage();
 await page.goto('http://localhost:3147/admin',{waitUntil:'networkidle'});
 await page.getByRole('navigation',{name:'Studio navigation'}).waitFor();
 const nav=page.getByRole('navigation',{name:'Studio navigation'});
 assert.equal(await nav.getByRole('link',{name:'Dashboard',exact:true}).count(),1);
 assert.equal(await page.getByText('Switch to portal').count(),0);
 await page.screenshot({path:out+'/desktop.png',fullPage:true});
 const desktopAxe=await new AxeBuilder({page}).include('nav[aria-label="Studio navigation"]').analyze();
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Open navigation'}).click();
 const dialog=page.getByRole('dialog',{name:'Studio navigation'});
 await dialog.waitFor();
 const bounds = await dialog.boundingBox();
 assert.ok(bounds.height >= 844, 'mobile drawer must cover the full viewport');
 assert.equal(await dialog.getByRole('link',{name:'Dashboard',exact:true}).count(),1);
 assert.equal(await dialog.getByRole('link',{name:'Proposals',exact:true}).count(),1);
 const focused=await page.evaluate(()=>document.activeElement?.getAttribute('href'));
 assert.equal(focused,'/admin');
 await page.screenshot({path:out+'/mobile.png',fullPage:true});
 const mobileAxe=await new AxeBuilder({page}).include('#portal-mobile-nav').analyze();
 await page.keyboard.press('Escape');
 assert.equal(await page.getByRole('button',{name:'Open navigation'}).getAttribute('aria-expanded'),'false');
 assert.equal(await page.evaluate(()=>document.activeElement?.getAttribute('aria-label')),'Open navigation');
 const report={scope:'local-only fake database, existing development-only admin preview, reduced motion',desktopNavigation:{dashboardCount:1,violations:desktopAxe.violations},mobileNavigation:{dashboardCount:1,keyboardFocus:true,escapeAndFocusRestore:true,violations:mobileAxe.violations}};
 await writeFile(out+'/report.json',JSON.stringify(report,null,2));
 assert.equal(desktopAxe.violations.length,0, 'desktop navigation must pass axe');
 assert.equal(mobileAxe.violations.length,0, 'mobile navigation must pass axe');
 console.log(JSON.stringify({out,desktopViolations:desktopAxe.violations.map(x=>({id:x.id,nodes:x.nodes.map(y=>y.target)})),mobileViolations:mobileAxe.violations.map(x=>({id:x.id,nodes:x.nodes.map(y=>y.target)}))}));
}finally{await browser.close();}
